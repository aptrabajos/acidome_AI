#!/usr/bin/env node

/**
 * ACIDOME Auto-Instrumenter
 *
 * Script Node.js que procesa el archivo HTML monolítico original
 * e inyecta código de instrumentación en cada función
 *
 * Usage:
 *   node auto-instrumenter.js <input.html> <output.html>
 *
 * @version 1.0.0
 */

const fs = require('fs');
const path = require('path');

class AutoInstrumenter {
    constructor(config = {}) {
        this.config = {
            instrumentFunctions: true,
            instrumentMethods: true,
            instrumentConstructors: true,
            skipMinified: true,
            verbose: true,
            ...config
        };

        this.stats = {
            totalFunctions: 0,
            instrumentedFunctions: 0,
            skippedFunctions: 0,
            errors: []
        };
    }

    /**
     * Procesa archivo HTML
     */
    async processFile(inputPath, outputPath) {
        console.log(`[Auto-Instrumenter] Reading: ${inputPath}`);

        const content = fs.readFileSync(inputPath, 'utf-8');

        console.log(`[Auto-Instrumenter] File size: ${(content.length / 1024).toFixed(2)} KB`);

        // Extraer JavaScript del HTML
        const instrumented = this.instrumentHTML(content);

        // Guardar archivo instrumentado
        fs.writeFileSync(outputPath, instrumented, 'utf-8');

        console.log(`[Auto-Instrumenter] Written: ${outputPath}`);
        console.log(`[Auto-Instrumenter] Stats:`, this.stats);

        return this.stats;
    }

    /**
     * Instrumenta archivo HTML
     */
    instrumentHTML(html) {
        // Encontrar todas las etiquetas <script>
        const scriptRegex = /<script[^>]*>([\s\S]*?)<\/script>/gi;

        let instrumentedHTML = html;
        let match;
        let offset = 0;

        // Inyectar herramientas de instrumentación ANTES del primer script
        const firstScriptIndex = html.search(scriptRegex);
        if (firstScriptIndex !== -1) {
            const instrumentationScripts = this.getInstrumentationScripts();
            instrumentedHTML =
                html.slice(0, firstScriptIndex) +
                instrumentationScripts +
                html.slice(firstScriptIndex);

            offset = instrumentationScripts.length;
        }

        // Instrumentar cada bloque de script
        scriptRegex.lastIndex = 0; // Reset regex
        while ((match = scriptRegex.exec(html)) !== null) {
            const scriptContent = match[1];
            const scriptStart = match.index + offset;
            const contentStart = scriptStart + match[0].indexOf(scriptContent);

            // Skip si es minified
            if (this.isMinified(scriptContent)) {
                console.log('[Auto-Instrumenter] Skipping minified script block');
                this.stats.skippedFunctions++;
                continue;
            }

            // Instrumentar JavaScript
            const instrumentedJS = this.instrumentJavaScript(scriptContent);

            // Reemplazar en HTML
            instrumentedHTML =
                instrumentedHTML.slice(0, contentStart) +
                instrumentedJS +
                instrumentedHTML.slice(contentStart + scriptContent.length);

            offset += (instrumentedJS.length - scriptContent.length);
        }

        return instrumentedHTML;
    }

    /**
     * Genera scripts de instrumentación para inyectar
     */
    getInstrumentationScripts() {
        return `
<!-- ============================================ -->
<!-- ACIDOME INSTRUMENTATION SCRIPTS -->
<!-- Auto-generated by auto-instrumenter.js -->
<!-- ============================================ -->

<script src="instrumentation/logger.js"></script>
<script src="instrumentation/profiler.js"></script>
<script src="instrumentation/data-capturer.js"></script>

<script>
// Configurar sistema de instrumentación
window.ACIDOME_INSTRUMENTATION = {
    enabled: true,
    logger: window.acidomeLogger,
    profiler: window.acidomeProfiler,
    capturer: window.acidomeDataCapturer
};

console.log('[ACIDOME] Instrumentation ready');
</script>

<!-- ============================================ -->
`;
    }

    /**
     * Detecta si JavaScript está minificado
     */
    isMinified(code) {
        const lines = code.split('\n');
        const avgLineLength = code.length / lines.length;

        // Heurística: minificado si promedio de línea > 200 chars
        return avgLineLength > 200;
    }

    /**
     * Instrumenta código JavaScript
     */
    instrumentJavaScript(code) {
        let instrumented = code;

        // Instrumentar function declarations
        instrumented = this.instrumentFunctionDeclarations(instrumented);

        // Instrumentar function expressions
        instrumented = this.instrumentFunctionExpressions(instrumented);

        // Instrumentar métodos de objetos
        instrumented = this.instrumentObjectMethods(instrumented);

        // Instrumentar prototype methods
        instrumented = this.instrumentPrototypeMethods(instrumented);

        return instrumented;
    }

    /**
     * Instrumenta function declarations
     * Ejemplo: function myFunction(a, b) { ... }
     */
    instrumentFunctionDeclarations(code) {
        const regex = /function\s+([a-zA-Z_$][a-zA-Z0-9_$]*)\s*\(([^)]*)\)\s*\{/g;

        return code.replace(regex, (match, functionName, params) => {
            this.stats.totalFunctions++;
            this.stats.instrumentedFunctions++;

            const instrumentation = this.generateFunctionInstrumentation(functionName, 'Global', params);

            return `function ${functionName}(${params}) {\n${instrumentation}\n`;
        });
    }

    /**
     * Instrumenta function expressions
     * Ejemplo: const myFunc = function(a, b) { ... }
     */
    instrumentFunctionExpressions(code) {
        const regex = /([a-zA-Z_$][a-zA-Z0-9_$]*)\s*=\s*function\s*\(([^)]*)\)\s*\{/g;

        return code.replace(regex, (match, varName, params) => {
            this.stats.totalFunctions++;
            this.stats.instrumentedFunctions++;

            const instrumentation = this.generateFunctionInstrumentation(varName, 'Global', params);

            return `${varName} = function(${params}) {\n${instrumentation}\n`;
        });
    }

    /**
     * Instrumenta métodos de objetos literales
     * Ejemplo: { myMethod: function() { ... } }
     */
    instrumentObjectMethods(code) {
        const regex = /([a-zA-Z_$][a-zA-Z0-9_$]*)\s*:\s*function\s*\(([^)]*)\)\s*\{/g;

        return code.replace(regex, (match, methodName, params) => {
            this.stats.totalFunctions++;
            this.stats.instrumentedFunctions++;

            const instrumentation = this.generateFunctionInstrumentation(methodName, 'Object', params);

            return `${methodName}: function(${params}) {\n${instrumentation}\n`;
        });
    }

    /**
     * Instrumenta prototype methods
     * Ejemplo: MyClass.prototype.myMethod = function() { ... }
     */
    instrumentPrototypeMethods(code) {
        const regex = /([a-zA-Z_$][a-zA-Z0-9_$]*)\.prototype\.([a-zA-Z_$][a-zA-Z0-9_$]*)\s*=\s*function\s*\(([^)]*)\)\s*\{/g;

        return code.replace(regex, (match, className, methodName, params) => {
            this.stats.totalFunctions++;
            this.stats.instrumentedFunctions++;

            const functionId = `${className}.${methodName}`;
            const instrumentation = this.generateFunctionInstrumentation(methodName, className, params);

            return `${className}.prototype.${methodName} = function(${params}) {\n${instrumentation}\n`;
        });
    }

    /**
     * Genera código de instrumentación para insertar en función
     */
    generateFunctionInstrumentation(functionName, module, params) {
        const paramsArray = params.split(',').map(p => p.trim()).filter(p => p);

        return `    // === INSTRUMENTATION START ===
    const __functionId = '${module}.${functionName}';
    const __args = [${paramsArray.join(', ')}];
    const __profileId = window.ACIDOME_INSTRUMENTATION?.profiler?.start(__functionId);

    const __originalFunction = () => {`;
    }

    /**
     * Genera cierre de instrumentación
     */
    generateInstrumentationEnd() {
        return `    };

    try {
        const __result = __originalFunction();

        // Capturar datos
        if (window.ACIDOME_INSTRUMENTATION?.capturer) {
            window.ACIDOME_INSTRUMENTATION.capturer.capture(__functionId, __args, __result);
        }

        // Finalizar profiling
        if (__profileId && window.ACIDOME_INSTRUMENTATION?.profiler) {
            window.ACIDOME_INSTRUMENTATION.profiler.end(__profileId);
        }

        // Log
        if (window.ACIDOME_INSTRUMENTATION?.logger) {
            window.ACIDOME_INSTRUMENTATION.logger.instrument(() => __result, __functionId.split('.')[1], __functionId.split('.')[0]);
        }

        return __result;
    } catch (error) {
        // Log error
        if (window.ACIDOME_INSTRUMENTATION?.logger) {
            console.error(\`[Instrumentation Error] \${__functionId}:\`, error);
        }

        // Finalizar profiling
        if (__profileId && window.ACIDOME_INSTRUMENTATION?.profiler) {
            window.ACIDOME_INSTRUMENTATION.profiler.end(__profileId);
        }

        throw error;
    }
    // === INSTRUMENTATION END ===`;
    }
}

// CLI Usage
if (require.main === module) {
    const args = process.argv.slice(2);

    if (args.length < 2) {
        console.error('Usage: node auto-instrumenter.js <input.html> <output.html>');
        process.exit(1);
    }

    const [inputPath, outputPath] = args;

    const instrumenter = new AutoInstrumenter({
        verbose: true
    });

    instrumenter.processFile(inputPath, outputPath)
        .then(stats => {
            console.log('\n[Auto-Instrumenter] ✅ Success!');
            console.log(`  Total functions found: ${stats.totalFunctions}`);
            console.log(`  Instrumented: ${stats.instrumentedFunctions}`);
            console.log(`  Skipped: ${stats.skippedFunctions}`);
        })
        .catch(error => {
            console.error('\n[Auto-Instrumenter] ❌ Error:', error);
            process.exit(1);
        });
}

module.exports = AutoInstrumenter;
